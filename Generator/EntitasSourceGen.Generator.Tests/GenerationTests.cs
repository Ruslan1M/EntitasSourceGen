using NUnit.Framework;
using static EntitasSourceGen.Generator.Tests.GeneratorHarness;

namespace EntitasSourceGen.Generator.Tests;

public class GenerationTests
{
    private const string Components = @"
using Entitas;
using EntitasSourceGen;

[Game] public sealed class PositionComponent : IComponent { public float X; public float Y; }
[Game] public sealed class AliveComponent : IComponent { }
[Game, Unique] public sealed class ScoreComponent : IComponent { public int Value; }
[Game, Unique] public sealed class PausedComponent : IComponent { }
[Game, Input] public sealed class TickComponent : IComponent { public long Value; }
[Game] public sealed class ObjectComponent : IComponent { public System.Collections.Generic.List<int> @int; }
";

    private const string Usage = @"
public static class Usage
{
    public static void Run()
    {
        var contexts = new Contexts();
        var e = contexts.game.CreateEntity();
        e.AddPosition(1f, 2f);
        e.ReplacePosition(3f, 4f);
        float x = e.position.X;
        bool has = e.hasPosition;
        e.RemovePosition();
        e.isAlive = true;
        e.AddObject(null);
        var o = e.@object.@int;

        contexts.game.SetScore(1);
        contexts.game.ReplaceScore(2);
        int s = contexts.game.score.Value;
        GameEntity se = contexts.game.scoreEntity;
        contexts.game.RemoveScore();
        contexts.game.isPaused = true;
        GameEntity pe = contexts.game.pausedEntity;

        contexts.input.CreateEntity().AddTick(1);
        Entitas.IMatcher<GameEntity> m = GameMatcher.AllOf(GameMatcher.Position, GameMatcher.Alive);
        Entitas.IMatcher<InputEntity> mi = InputMatcher.AnyOf(InputMatcher.Tick);
        int idx = GameComponentsLookup.Position + GameComponentsLookup.TotalComponents;
        Entitas.IContext[] all = contexts.allContexts;
        contexts.Reset();
    }
}
";

    [Test]
    public void GeneratedCode_CompilesAsCSharp9()
    {
        var result = Run(Marker, ContextAttributes, Components, Usage);

        Assert.That(result.GeneratorDiagnostics.Where(d => d.Severity == Microsoft.CodeAnalysis.DiagnosticSeverity.Error), Is.Empty);
        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
    }

    [Test]
    public void Generates_ExpectedFiles()
    {
        var result = Run(Marker, ContextAttributes, Components);

        Assert.That(result.Sources.Select(s => s.HintName), Is.EquivalentTo(new[]
        {
            "Contexts.g.cs",
            "Game.Lookup.g.cs", "Game.Context.g.cs", "Game.Entity.g.cs", "Game.Matcher.g.cs", "Game.Unique.g.cs",
            "Input.Lookup.g.cs", "Input.Context.g.cs", "Input.Entity.g.cs", "Input.Matcher.g.cs",
            "Feature.g.cs",
        }));
    }

    [Test]
    public void EveryFile_HasHeader()
    {
        foreach (var source in Run(Marker, ContextAttributes, Components).Sources)
        {
            var text = source.SourceText.ToString();
            Assert.That(text, Does.StartWith("// <auto-generated/>"), source.HintName);
            Assert.That(text, Does.Contain("#nullable disable"), source.HintName);
        }
    }

    [Test]
    public void Indices_AreSortedByName()
    {
        var lookup = Run(Marker, ContextAttributes, Components).Source("Game.Lookup.g.cs");

        Assert.That(lookup, Does.Contain("public const int Alive = 0;"));
        Assert.That(lookup, Does.Contain("public const int Object = 1;"));
        Assert.That(lookup, Does.Contain("public const int Paused = 2;"));
        Assert.That(lookup, Does.Contain("public const int Position = 3;"));
        Assert.That(lookup, Does.Contain("public const int Score = 4;"));
        Assert.That(lookup, Does.Contain("public const int Tick = 5;"));
        Assert.That(lookup, Does.Contain("public const int TotalComponents = 6;"));
    }

    [Test]
    public void Singleton_OffByDefault_OnWhenRequested()
    {
        Assert.That(Run(Marker, ContextAttributes, Components).Source("Contexts.g.cs"), Does.Not.Contain("sharedInstance"));

        var on = Run("[assembly: EntitasSourceGen.EntitasSourceGen(Singleton = true)]", ContextAttributes, Components,
            "public static class U { public static Contexts C() => Contexts.sharedInstance; }");
        Assert.That(on.CompileErrors, Is.Empty, string.Join("\n", on.CompileErrors));
    }

    [Test]
    public void Namespace_IsApplied()
    {
        var result = Run("[assembly: EntitasSourceGen.EntitasSourceGen(Namespace = \"My.Game\")]", ContextAttributes, Components,
            "namespace My.Game { public static class U { public static GameEntity E(Contexts c) => c.game.CreateEntity(); } }");

        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
        Assert.That(result.Source("Game.Entity.g.cs"), Does.Contain("namespace My.Game"));
    }

    [Test]
    public void DeclaredContextWithoutComponents_IsGenerated()
    {
        var result = Run(Marker, ContextAttributes, "[Game] public sealed class AComponent : Entitas.IComponent { }",
            "public static class U { public static InputEntity E(Contexts c) => c.input.CreateEntity(); }");

        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
        Assert.That(result.Source("Input.Lookup.g.cs"), Does.Contain("TotalComponents = 0"));
    }

    [Test]
    public void ComponentWithoutSuffix_KeepsName()
    {
        var result = Run(Marker, ContextAttributes, "[Game] public sealed class Health : Entitas.IComponent { public int Value; }",
            "public static class U { public static void R(GameEntity e) { e.AddHealth(1); var h = e.health; } }");

        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
    }

    [Test]
    public void Members_IncludeInheritedFieldsAndProperties_SkipReadonly()
    {
        var result = Run(Marker, ContextAttributes, @"
public class BaseData { public int A; }
[Game] public sealed class MixComponent : BaseData, Entitas.IComponent
{
    public int B { get; set; }
    public readonly int Skipped1;
    public int Skipped2 { get; }
    public int value;
    public int Value;
}",
            "public static class U { public static void R(GameEntity e) { e.AddMix(1, 2, 3, 4); var m = e.mix; int s = m.A + m.B + m.value + m.Value; } }");

        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
        Assert.That(result.Source("Game.Entity.g.cs"), Does.Contain("AddMix(int newA, int newB, int newValue, int newValue2)"));
    }

    [Test]
    public void KeywordNamedComponent_IsEscaped()
    {
        var result = Run(Marker, ContextAttributes, "[Game] public sealed class @int : Entitas.IComponent { public int Value; }",
            "public static class U { public static void R(GameEntity e) { e.Addint(1); var x = e.@int; var m = GameMatcher.@int; int i = GameComponentsLookup.@int; } }");

        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
    }

    [Test]
    public void GeneratedTypes_AreGlobalQualified()
    {
        var result = Run("[assembly: EntitasSourceGen.EntitasSourceGen(Namespace = \"My.Game\")]", ContextAttributes, Components);

        Assert.That(result.Source("Game.Context.g.cs"), Does.Contain("global::Entitas.Context<global::My.Game.GameEntity>"));
        Assert.That(result.Source("Game.Entity.g.cs"), Does.Contain("global::My.Game.GameComponentsLookup.Position"));
    }

    [Test]
    public void BrokenUserCode_AfterRename_StillGenerates()
    {
        // Component renamed Old -> New, a call site still uses the old API: compilation is broken.
        var result = Run(Marker, ContextAttributes,
            "[Game] public sealed class NewComponent : Entitas.IComponent { public int Value; }",
            "public static class U { public static void R(GameEntity e) { e.AddOld(1); e.AddNew(2); } }");

        Assert.That(result.RunResult.Results.Single().Exception, Is.Null);
        Assert.That(result.GeneratorDiagnostics.Where(d => d.Id == "CS8785"), Is.Empty);
        Assert.That(result.Source("Game.Entity.g.cs"), Does.Contain("AddNew"));
        Assert.That(result.CompileErrors.Select(e => e.Id), Is.EquivalentTo(new[] { "CS1061" }));
    }

    [Test]
    public void RecordClassComponent_IsSupported()
    {
        var result = Run(Marker, ContextAttributes, "[Game] public sealed record HpComponent : Entitas.IComponent { public int Value; }",
            "public static class U { public static void R(GameEntity e) { e.AddHp(1); } }");
        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
    }

    [Test]
    public void InvalidNamespace_FallsBackToGlobal_WithWarning()
    {
        var result = Run("[assembly: EntitasSourceGen.EntitasSourceGen(Namespace = \"My-Game\")]", ContextAttributes, Components,
            "public static class U { public static GameEntity E(Contexts c) => c.game.CreateEntity(); }");
        Assert.That(result.GeneratorDiagnostics.Single(d => d.Id == "ECG010").GetMessage(), Does.Contain("My-Game"));
        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
    }

    [Test]
    public void NestedComponentWithoutContext_IsOnlyWarning()
    {
        var result = Run(Marker, ContextAttributes, "public class Outer { public sealed class InnerComponent : Entitas.IComponent { } }",
            "[Game] public sealed class AComponent : Entitas.IComponent { }");
        Assert.That(result.GeneratorDiagnostics.Select(d => d.Id), Is.EquivalentTo(new[] { "ECG001" }));
    }

    [Test]
    public void PartialComponent_GeneratedOnce()
    {
        var result = Run(Marker, ContextAttributes,
            "[Game] public sealed partial class HpComponent : Entitas.IComponent { public int Value; }",
            "public sealed partial class HpComponent : Entitas.IComponent { }");

        Assert.That(result.CompileErrors, Is.Empty, string.Join("\n", result.CompileErrors));
        Assert.That(result.Source("Game.Lookup.g.cs"), Does.Contain("TotalComponents = 1"));
    }
}
