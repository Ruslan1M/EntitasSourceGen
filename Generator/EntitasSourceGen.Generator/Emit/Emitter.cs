using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using EntitasSourceGen.Generator.Config;
using EntitasSourceGen.Generator.Model;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace EntitasSourceGen.Generator.Emit;

/// <summary>
/// Context of one emit call: the context model plus the <c>global::</c> qualifier of generated types.
/// Declarations use bare names (<see cref="Entity"/>), references use qualified ones (<see cref="EntityRef"/>).
/// </summary>
internal readonly struct Scope
{
    public Scope(ContextModel ctx, string qualifier)
    {
        Ctx = ctx;
        Q = qualifier;
    }

    public ContextModel Ctx { get; }
    public string Q { get; }

    public string Entity => Ctx.Name + "Entity";
    public string Context => Ctx.Name + "Context";
    public string Matcher => Ctx.Name + "Matcher";
    public string Lookup => Ctx.Name + "ComponentsLookup";

    public string EntityRef => Q + Entity;
    public string ContextRef => Q + Context;
    public string MatcherRef => Q + Matcher;
    public string LookupRef => Q + Lookup;

    public string IndexRef(ComponentModel c) => $"{LookupRef}.{c.Id}";
    public string MatcherOf(ComponentModel c) => $"{MatcherRef}.{c.Id}";
}

/// <summary>Writes every generated file. Each emitter fills the body inside the namespace.</summary>
internal static class Emitter
{
    public static void EmitAll(SourceProductionContext spc, GeneratorConfig config, AnalysisResult analysis)
    {
        var contexts = analysis.Contexts;
        var q = Qualifier(config);
        foreach (var ctx in contexts)
        {
            var s = new Scope(ctx, q);
            Add(spc, config, $"{ctx.Name}.Lookup.g.cs", w => LookupEmitter.Emit(w, s));
            Add(spc, config, $"{ctx.Name}.Context.g.cs", w => ContextEmitter.Emit(w, s));
            Add(spc, config, $"{ctx.Name}.Entity.g.cs", w => EntityEmitter.Emit(w, s));
            Add(spc, config, $"{ctx.Name}.Matcher.g.cs", w => MatcherEmitter.Emit(w, s));
            if (UniqueEmitter.HasAny(ctx))
                Add(spc, config, $"{ctx.Name}.Unique.g.cs", w => UniqueEmitter.Emit(w, s));
            if (IndexEmitter.HasAny(ctx))
                Add(spc, config, $"{ctx.Name}.EntityIndices.g.cs", w => IndexEmitter.EmitContext(w, s, q));
            if (!ctx.Events.IsEmpty)
                Add(spc, config, $"{ctx.Name}.Events.g.cs", w => EventEmitter.Emit(w, s));
            if (!ctx.Cleanups.IsEmpty)
                Add(spc, config, $"{ctx.Name}.Cleanup.g.cs", w => CleanupEmitter.Emit(w, s));
        }

        if (analysis.GenerateFeature)
            Add(spc, config, "Feature.g.cs", w => FeatureEmitter.Emit(w, config));

        if (!analysis.Interfaces.IsEmpty)
            Add(spc, config, "Components.Interfaces.g.cs", w => EntityEmitter.EmitInterfaces(w, analysis.Interfaces));

        if (contexts.Any(IndexEmitter.HasAny))
            Add(spc, config, "Contexts.EntityIndices.g.cs", w => IndexEmitter.EmitContexts(w, contexts, q));

        Add(spc, config, "Contexts.g.cs", w => ContextsEmitter.Emit(w, config, contexts, q));
    }

    public static string Qualifier(GeneratorConfig config)
        => config.Namespace is null ? "global::" : $"global::{config.Namespace}.";

    public static string Render(GeneratorConfig config, Action<CodeWriter> body)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("// Generated by EntitasSourceGen. Do not edit.");
        w.Raw("#nullable disable");
        w.Line();

        if (config.Namespace is null)
        {
            body(w);
        }
        else
        {
            w.Open($"namespace {config.Namespace}");
            body(w);
            w.Close();
        }

        return w.ToString();
    }

    private static void Add(SourceProductionContext spc, GeneratorConfig config, string hintName, Action<CodeWriter> body)
        => spc.AddSource(hintName, SourceText.From(Render(config, body), Encoding.UTF8));

    /// <summary>Parameter names for a component's members: <c>Value</c> → <c>newValue</c>, deduplicated.</summary>
    public static IReadOnlyList<string> ParamNames(ComponentModel c)
    {
        var result = new List<string>(c.Fields.Length);
        var used = new HashSet<string>();
        foreach (var f in c.Fields)
        {
            var name = Names.NewParam(f.Name);
            var unique = name;
            for (var i = 2; !used.Add(unique); i++) unique = name + i;
            result.Add(unique);
        }
        return result;
    }

    public static string ParamList(ComponentModel c)
    {
        var names = ParamNames(c);
        var sb = new StringBuilder();
        for (var i = 0; i < c.Fields.Length; i++)
        {
            if (i > 0) sb.Append(", ");
            sb.Append(c.Fields[i].Type).Append(' ').Append(names[i]);
        }
        return sb.ToString();
    }

    public static string ArgList(ComponentModel c) => string.Join(", ", ParamNames(c));
}
